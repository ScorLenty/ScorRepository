#include <iostream>
#include <clocale>

using namespace std;

// Рекурсивная функция перекладывания ингредиентов (Ханойские башни)
void hanoi(int n, int from, int to, int aux)
{
    if (n == 0)
    {
        return;
    }
    // Перекладываем n-1 меньших ингредиентов на вспомогательную салфетку
    hanoi(n - 1, from, aux, to);
    // Перекладываем самый большой текущий ингредиент на нужную салфетку
    cout << "Ингредиент " << n << " переложить с салфетки " << from << " на салфетку " << to << "\n";
    // Перекладываем n-1 ингредиентов со вспомогательной на нужную салфетку
    hanoi(n - 1, aux, to, from);
}

int main()
{
    // Подключение русской локализации для корректного вывода кириллицы в консоль
    setlocale(LC_ALL, "Russian");

    int n;
    cout << "Введите количество ингредиентов: ";
    cin >> n;

    // Перекладываем с 1-й салфетки на 3-ю, используя 2-ю как вспомогательную
    hanoi(n, 1, 3, 2);

    return 0;
}